static void ssd1306_cmd(ssd1306_t* disp, uint8_t cmd) {
	uint8_t buf[2] = { 0x00, cmd };
	i2c_write_blocking(disp->i2c, SSD1306_I2C_ADDR, buf, 2, false);
}

void ssd1306_init(ssd1306_t* disp, i2c_inst_t* i2c) {
	disp->i2c = i2c;

	// Command initialization byte sequence for standard 128x64 SSD1306 OLED
	uint8_t cmds[] = {
		0xAE,       // Display OFF
		0x20, 0x00, // Set Memory Addressing Mode to Horizontal Addressing Mode
		0xB0,       // Set Page Start Address for Page Addressing Mode to 0
		0xC8,       // Set COM Output Scan Direction (remapped mode)
		0x00,       // Set low column address
		0x10,       // Set high column address
		0x40,       // Set start line address
		0x81, 0x7F, // Set contrast control register to mid-scale
		0xA1,       // Set segment re-map (A0h/A1h)
		0xA6,       // Set normal display mode (A6h=normal, A7h=inverse)
		0xA8, 0x3F, // Set multiplex ratio to 1/64 duty (64 lines)
		0xD3, 0x00, // Set display offset to 0
		0xD5, 0x80, // Set display clock divide ratio/oscillator frequency
		0xD9, 0xF1, // Set pre-charge period
		0xDA, 0x12, // Set COM pins hardware configuration
		0xDB, 0x40, // Set VCOMH deselect level
		0x8D, 0x14, // Enable charge pump regulator
		0xAF        // Display ON
	};

	for (size_t i = 0; i < sizeof(cmds); i++) {
		ssd1306_cmd(disp, cmds[i]);
	}

	ssd1306_clear(disp);
}

void ssd1306_clear(ssd1306_t* disp) {
	memset(disp->buffer, 0, sizeof(disp->buffer));
}

static inline void ssd1306_draw_pixel(ssd1306_t* disp, int x, int y,
	bool turn_on) {
	if (x < 0 || x >= 128 || y < 0 || y >= 64) {
		return; // Bounds check
	}

	int page = y / 8;
	int bit = y % 8;
	int index = page * 128 + x;

	if (turn_on) {
		disp->buffer[index] |= (1 << bit);
	} else {
		disp->buffer[index] &= ~(1 << bit);
	}
}

void ssd1306_draw_string(ssd1306_t* disp, int x, int y, const char* str) {
	ssd1306_draw_string_scaled(disp, x, y, str, SSD1306_FONT_NORMAL);
}

void ssd1306_draw_string_double(ssd1306_t* disp, int x, int y,
	const char* str) {
	ssd1306_draw_string_scaled(disp, x, y, str, SSD1306_FONT_DOUBLE);
}

void ssd1306_draw_string_scaled(ssd1306_t* disp, int x, int y, const char* str,
	uint8_t scale) {
	if (scale < SSD1306_FONT_NORMAL) scale = SSD1306_FONT_NORMAL;
	if (scale > SSD1306_FONT_DOUBLE) scale = SSD1306_FONT_DOUBLE;

	while (*str) {
		char c = *str++;

		// Handle out-of-bounds ASCII values
		if (c < 0x20 || c > 0x7E) {
			c = '?';
		}

		uint8_t idx = c - 0x20; // Index into 0x20..0x7E font table

		// Iterate across 5 horizontal font columns
		for (int col = 0; col < 5; col++) {
			uint8_t line = font5x7[idx][col];

			// Iterate down 7 vertical bits of the column byte
			for (int bit = 0; bit < 7; bit++) {
				bool pixel_active = (line & (1 << bit)) != 0;

				if (pixel_active) {
					// Render scaled pixel blocks
					for (int sx = 0; sx < scale; sx++) {
						for (int sy = 0; sy < scale; sy++) {
							ssd1306_draw_pixel(
								disp,
								x + (col * scale) + sx,
								y + (bit * scale) + sy,
								true
							);
						}
					}
				}
			}
		}

		// Advance horizontal position
		// (5 font columns + 1 pixel padding) * scale
		x += (6 * scale);
	}
}

void ssd1306_show(ssd1306_t* disp) {
	// Set column address range (0 to 127)
	ssd1306_cmd(disp, 0x21);
	ssd1306_cmd(disp, 0);
	ssd1306_cmd(disp, 127);

	// Set page address range (0 to 7)
	ssd1306_cmd(disp, 0x22);
	ssd1306_cmd(disp, 0);
	ssd1306_cmd(disp, 7);

	// Transmit data stream prefix byte (0x40) followed by
	// 1024 frame buffer bytes
	uint8_t payload[1025];
	payload[0] = 0x40; // Co = 0, D/C# = 1 (Data mode)
	memcpy(&payload[1], disp->buffer, 1024);

	i2c_write_blocking(disp->i2c, SSD1306_I2C_ADDR, payload, 1025, false);
}
